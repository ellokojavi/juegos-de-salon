#!/usr/bin/env node
/**
 * Every job of Juegos de Salón, in one place (D-365). The registry is `tools/jobs/jobs.json`; each
 * job runs in one of four places:
 *
 *   github  a scheduled workflow in .github/workflows/ (its cron must match the registry's)
 *   mac     a launchd job on the owner's Mac mini, installed from the registry by this tool; it
 *           runs a plain script, with no Claude unless the script itself decides it needs one
 *   app     a scheduled task in the Claude app (it opens a Claude session every time it runs)
 *   hook    a Claude Code hook in .claude/settings.json
 *
 * A job that runs often and usually finds nothing to do is a `mac` job: checking costs nothing,
 * and only the work found costs tokens.
 *
 *   node tools/jobs/jobs.mjs status            # every job, where it runs and its last run
 *   node tools/jobs/jobs.mjs install           # writes and loads the launchd jobs (`mac`)
 *   node tools/jobs/jobs.mjs uninstall <id>    # unloads one and deletes its plist
 *   node tools/jobs/jobs.mjs run <id>          # what launchd runs: lock, log, last-run record
 *
 * launchd runs the code of the main folder (the first entry of `git worktree list`), which stays
 * on `main`: a job changes when its PR merges and the folder is pulled, not when it is installed.
 * Logs in ~/Library/Logs/juegos-de-salon/<id>.log, last run in ~/.config/juegos-de-salon/jobs/<id>.json.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync, unlinkSync, appendFileSync, rmSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync, spawnSync } from 'node:child_process';

const HERE = dirname(fileURLToPath(import.meta.url));
export const REGISTRY = join(HERE, 'jobs.json');
export const LABEL = id => `cl.juegosdesalon.${id}`;
const LOGS = join(homedir(), 'Library/Logs/juegos-de-salon');
const STATE = join(homedir(), '.config/juegos-de-salon/jobs');
const AGENTS = join(homedir(), 'Library/LaunchAgents');

export const jobs = (file = REGISTRY) => JSON.parse(readFileSync(file, 'utf8')).jobs;

/** The main folder: launchd runs its code, never a worktree's. */
export function mainFolder() {
  const out = execFileSync('git', ['worktree', 'list', '--porcelain'], { cwd: HERE, encoding: 'utf8' });
  return /^worktree (.+)$/m.exec(out)[1];
}

/** The launchd plist of a `mac` job (pure, tested). */
export function plist(job, { repo, node, path, user = 'owner' }) {
  // USER and LOGNAME: without them claude and gh don't find their sign-in in the keychain
  const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;');
  const args = [node, join(repo, 'tools/jobs/jobs.mjs'), 'run', job.id];
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by tools/jobs/jobs.mjs install from tools/jobs/jobs.json (D-365): do not edit -->
<plist version="1.0">
<dict>
  <key>Label</key><string>${LABEL(job.id)}</string>
  <key>ProgramArguments</key>
  <array>${args.map(a => `<string>${esc(a)}</string>`).join('')}</array>
  <key>WorkingDirectory</key><string>${esc(repo)}</string>
  <key>EnvironmentVariables</key>
  <dict><key>PATH</key><string>${esc(path)}</string><key>USER</key><string>${esc(user)}</string><key>LOGNAME</key><string>${esc(user)}</string></dict>
  <key>StartInterval</key><integer>${job.every}</integer>
  <key>RunAtLoad</key><true/>
  <key>StandardOutPath</key><string>${esc(join(LOGS, `${job.id}.launchd.log`))}</string>
  <key>StandardErrorPath</key><string>${esc(join(LOGS, `${job.id}.launchd.log`))}</string>
</dict>
</plist>
`;
}

const ago = iso => {
  if (!iso) return 'never';
  const m = Math.round((Date.now() - new Date(iso)) / 60000);
  return m < 60 ? `${m} min ago` : m < 2880 ? `${Math.round(m / 60)} h ago` : `${Math.round(m / 1440)} d ago`;
};
const when = j => j.every ? `every ${j.every >= 3600 ? `${j.every / 3600} h` : `${j.every / 60} min`}` : j.cron ? `cron ${j.cron}` : j.trigger;

function lastRun(j) {
  if (j.where === 'mac') {
    const f = join(STATE, `${j.id}.json`);
    const loaded = spawnSync('launchctl', ['print', `gui/${process.getuid()}/${LABEL(j.id)}`]).status === 0;
    if (!existsSync(f)) return loaded ? 'installed, not run yet' : '⚠️ not installed (jobs.mjs install)';
    const s = JSON.parse(readFileSync(f, 'utf8'));
    return `${s.exit === 0 ? '✅' : '❌'} ${ago(s.at)} · ${s.summary || ''}${loaded ? '' : ' · ⚠️ not loaded'}`;
  }
  if (j.where === 'github') {
    try {
      const [r] = JSON.parse(execFileSync('gh', ['run', 'list', '--workflow', j.workflow, '--limit', '1', '--json', 'conclusion,createdAt,status'], { encoding: 'utf8' }));
      return r ? `${r.conclusion === 'success' ? '✅' : r.status !== 'completed' ? '⏳' : '❌'} ${ago(r.createdAt)}` : 'never';
    } catch { return '? (gh unavailable)'; }
  }
  if (j.where === 'app') return 'see the app → Scheduled';
  return 'runs on its trigger';
}

function status() {
  for (const j of jobs()) console.log(`${j.id.padEnd(17)} ${j.where.padEnd(7)} ${when(j).padEnd(26)} ${lastRun(j)}\n${' '.repeat(18)}${j.what}`);
}

function install() {
  const repo = mainFolder();
  const node = process.execPath;
  const path = [dirname(node), join(homedir(), '.local/bin'), '/opt/homebrew/bin', '/usr/local/bin', '/usr/bin', '/bin'].join(':');
  mkdirSync(LOGS, { recursive: true }); mkdirSync(AGENTS, { recursive: true });
  for (const j of jobs().filter(j => j.where === 'mac')) {
    const file = join(AGENTS, `${LABEL(j.id)}.plist`);
    spawnSync('launchctl', ['bootout', `gui/${process.getuid()}`, file]);
    writeFileSync(file, plist(j, { repo, node, path, user: process.env.USER }));
    execFileSync('launchctl', ['bootstrap', `gui/${process.getuid()}`, file]);
    console.log(`✓ ${LABEL(j.id)} (${when(j)}) → ${repo}`);
  }
}

function uninstall(id) {
  const file = join(AGENTS, `${LABEL(id)}.plist`);
  spawnSync('launchctl', ['bootout', `gui/${process.getuid()}`, file]);
  if (existsSync(file)) unlinkSync(file);
  console.log(`✓ ${LABEL(id)} removed`);
}

/**
 * The main folder catches up with origin/main before each run: nobody pulled it by hand, and on
 * 2026-10-22 the jobs were running code 215 commits old. Only a fast-forward, only on a clean `main`;
 * otherwise it runs what is there and says why.
 */
function catchUp(folder) {
  const git = (...a) => execFileSync('git', a, { cwd: folder, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  try {
    if (git('rev-parse', '--abbrev-ref', 'HEAD') !== 'main') return 'not on main, not updated';
    if (git('status', '--porcelain', '--untracked-files=no')) return 'uncommitted changes, not updated';
    git('pull', '--ff-only', '-q', 'origin', 'main');
    return '';
  } catch (e) { return `not updated: ${String(e.stderr || e.message).trim().split('\n')[0]}`; }
}

/** What launchd runs: one at a time, every line logged, the last run recorded for `status`. */
function run(id) {
  const j = jobs().find(x => x.id === id && x.where === 'mac');
  if (!j) throw new Error(`No mac job ${id} in jobs.json.`);
  mkdirSync(LOGS, { recursive: true }); mkdirSync(STATE, { recursive: true });
  const lock = join(STATE, `${id}.lock`);
  try { mkdirSync(lock); } catch { return; } // the previous run is still going
  const start = Date.now();
  try {
    const folder = mainFolder();
    const note = catchUp(folder);
    const r = spawnSync(j.command[0], j.command.slice(1), { cwd: folder, encoding: 'utf8', timeout: (j.timeout || 900) * 1000 });
    const out = `${note ? `(main folder ${note})\n` : ''}${r.stdout || ''}${r.stderr || ''}`.trim();
    const exit = r.status ?? 1;
    appendFileSync(join(LOGS, `${id}.log`), `── ${new Date(start).toISOString()} exit ${exit} ${Date.now() - start} ms\n${out}\n`);
    writeFileSync(join(STATE, `${id}.json`), JSON.stringify({ at: new Date(start).toISOString(), exit, ms: Date.now() - start, summary: out.split('\n').pop().slice(0, 120) }));
  } finally { rmSync(lock, { recursive: true, force: true }); }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [command, id] = process.argv.slice(2);
  try {
    if (command === 'status') status();
    else if (command === 'install') install();
    else if (command === 'uninstall' && id) uninstall(id);
    else if (command === 'run' && id) run(id);
    else { console.error('Usage: node tools/jobs/jobs.mjs status | install | uninstall <id> | run <id>'); process.exit(2); }
  } catch (e) { console.error(e.message); process.exit(1); }
}
