/**
 * The rule registry (D-541, docs/RULES.md): docs/rules.json holds every rule with its form, and the
 * index at the end of docs/RULES.md is generated from it.
 *
 *   node tools/agents/rules.mjs index           (rewrites the index block in docs/RULES.md)
 *   node tools/agents/rules.mjs index --check   (exit 1 if the block is stale)
 *   node tools/agents/rules.mjs problems        (what rules.test.mjs fails on)
 *   node tools/agents/rules.mjs report [--json] [--record]   (the processes agent's rules round, #1249 step 16)
 *
 * `report` gives three things: the debt of each 📈 rule (entries in its `debt` file) with its trend
 * since the last count recorded in docs/rules-debt.json (`--record` stores today's), every 👁 rule
 * without a reviewer, and "repeated fixes without a test" (docs/RULES.md rule 5). That last one is a
 * heuristic: it reads the subjects of the last 30 days of commits, keeps the ones that look like a
 * fix, and lists a rule id (C-n, U-n, D-n or a registry id) named by two or more of them when that
 * rule has no 🤖 or 📈 form. A candidate is a lead to judge, not a verdict.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const REGISTRY = join(ROOT, 'docs', 'rules.json');
const DOC = join(ROOT, 'docs', 'RULES.md');
export const DEBT_LOG = join(ROOT, 'docs', 'rules-debt.json');
const BEGIN = '<!-- rules-index:begin (generated by node tools/agents/rules.mjs index) -->';
const END = '<!-- rules-index:end -->';
export const FORMS = { check: '🤖', ratchet: '📈', judged: '👁' };

export const readRegistry = () => JSON.parse(readFileSync(REGISTRY, 'utf8')).rules;

/** Everything wrong with one rule, as messages; [] when it is complete. */
export function problemsOf(r, exists = p => existsSync(join(ROOT, p))) {
  const out = [];
  const where = r.id || '(no id)';
  if (!r.id || !r.title || !r.doc) out.push(`${where}: needs id, title and doc`);
  if (r.doc && !exists(r.doc)) out.push(`${where}: doc ${r.doc} does not exist`);
  const form = Array.isArray(r.form) ? r.form : [];
  if (!form.length) out.push(`${where}: no form (check, ratchet or judged)`);
  for (const f of form) if (!FORMS[f]) out.push(`${where}: unknown form "${f}"`);
  if (form.includes('check') || form.includes('ratchet')) {
    if (!r.enforcedBy?.length) out.push(`${where}: a check or ratchet names the files that enforce it (enforcedBy)`);
    for (const p of r.enforcedBy || []) if (!exists(p)) out.push(`${where}: enforcedBy ${p} does not exist`);
  }
  if (form.includes('ratchet') && (!r.debt || !exists(r.debt))) out.push(`${where}: a ratchet names its debt list (debt), and it exists`);
  if (r.exceptions && !exists(r.exceptions)) out.push(`${where}: exceptions ${r.exceptions} does not exist`);
  if (form.includes('judged') && (!r.reviewer || !r.why)) out.push(`${where}: a judged rule names its reviewer and why it cannot be measured`);
  return out;
}

export function problems(rules = readRegistry()) {
  const out = rules.flatMap(r => problemsOf(r));
  const seen = new Set();
  for (const r of rules) { if (seen.has(r.id)) out.push(`${r.id}: listed twice`); seen.add(r.id); }
  return out;
}

const mark = r => r.form.map(f => FORMS[f]).join('');
const cell = s => String(s).replace(/\|/g, '\\|');

export function renderIndex(rules = readRegistry()) {
  const count = f => rules.filter(r => r.form.includes(f)).length;
  const lines = [BEGIN, '',
    `${rules.length} rules: ${count('check')} 🤖 checked, ${count('ratchet')} 📈 ratcheted, ${count('judged')} 👁 judged (a rule with two marks counts in both).`, '',
    '| Rule | Form | Where | Enforced by / reviewer |', '|---|---|---|---|'];
  for (const r of rules) {
    const by = [...(r.enforcedBy || []).map(p => `\`${p}\``), r.debt && `debt \`${r.debt}\``, r.reviewer].filter(Boolean).join(', ');
    lines.push(`| ${cell(r.id)} · ${cell(r.title)} | ${mark(r)} | ${r.doc} | ${cell(by)} |`);
  }
  lines.push('', END);
  return lines.join('\n');
}

export function withIndex(doc, rules) {
  const block = renderIndex(rules);
  const a = doc.indexOf(BEGIN), b = doc.indexOf(END);
  if (a < 0 || b < 0) return `${doc.trimEnd()}\n\n## The index\n\n${block}\n`;
  return doc.slice(0, a) + block + doc.slice(b + END.length);
}

/** How many entries a debt file holds: an array's length or an object map's keys; docs/english-renames.json
 * (`paths`, each with a `state`) counts only its pending names. */
export function debtCount(data) {
  if (Array.isArray(data)) return data.length;
  if (!data || typeof data !== 'object') return 0;
  if (data.paths && typeof data.paths === 'object') return Object.values(data.paths).filter(v => v?.state === 'pending').length;
  if (data.pending !== undefined) return debtCount(data.pending);
  if (data.entries !== undefined) return debtCount(data.entries);
  return Object.entries(data).filter(([k, v]) => !(typeof v === 'string' && /^_?(about|policy)$/.test(k))).length;
}

export const FIX_SUBJECT = /\bfix(es|ed)?\b|\bcorrige|\barregla|fell behind|was missing|was wrong|\bforgot/i;
const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** Rule ids named by two or more fix subjects, among rules with no 🤖/📈 form (a heuristic, see above). */
export function repeatedFixes(subjects, rules) {
  const byId = Object.fromEntries(rules.map(r => [r.id, r]));
  const ids = rules.map(r => r.id).filter(id => !/^[CUDR]-\d+b?$/.test(id)).sort((a, b) => b.length - a.length);
  const named = new RegExp(`\\b([CUDR]-\\d+b?)\\b${ids.length ? `|(?<![\\w-])(${ids.map(esc).join('|')})(?![\\w-])` : ''}`, 'g');
  const seen = {};
  for (const s of subjects) {
    if (!FIX_SUBJECT.test(s)) continue;
    for (const id of new Set([...s.matchAll(named)].map(m => m[1] || m[2]))) (seen[id] ||= []).push(s);
  }
  return Object.entries(seen)
    .filter(([id, list]) => list.length >= 2 && !(byId[id]?.form || []).some(f => f === 'check' || f === 'ratchet'))
    .map(([id, list]) => ({ id, registered: !!byId[id], count: list.length, subjects: list }))
    .sort((a, b) => b.count - a.count || a.id.localeCompare(b.id));
}

/** The last count recorded for each rule before `date`, from {date: {rule: count}}. */
export function lastRecorded(log = {}, date = '9999') {
  const out = {};
  for (const d of Object.keys(log).sort()) if (d < date) Object.assign(out, log[d]);
  return out;
}

const readJson = p => JSON.parse(readFileSync(join(ROOT, p), 'utf8'));
export function buildReport({ rules = readRegistry(), read = readJson, subjects = [], log = {}, date = new Date().toISOString().slice(0, 10) } = {}) {
  const last = lastRecorded(log, date);
  const debt = rules.filter(r => r.form.includes('ratchet') && r.debt).map(r => {
    const count = debtCount(read(r.debt)), before = last[r.id];
    return { id: r.id, debt: r.debt, count, last: before ?? null, delta: before === undefined ? null : count - before };
  });
  const unreviewed = rules.filter(r => r.form.includes('judged') && !r.reviewer).map(r => r.id);
  return { date, debt, unreviewed, repeated: repeatedFixes(subjects, rules) };
}

export function formatReport(rep) {
  const trend = d => d.delta === null ? 'first count' : d.delta < 0 ? `shrank by ${-d.delta} since last round` : d.delta > 0 ? `grew by ${d.delta} since last round` : 'same as last round';
  const lines = ['📈 Debt per ratchet:'];
  for (const d of rep.debt) lines.push(`- ${d.id}: ${d.count} in ${d.debt} (${trend(d)})`);
  lines.push(`👁 Without reviewer: ${rep.unreviewed.length ? rep.unreviewed.join(', ') : 'none'}`,
    'Repeated fixes without a test (heuristic, last 30 days, docs/RULES.md rule 5):');
  if (!rep.repeated.length) lines.push('None.');
  for (const c of rep.repeated) {
    lines.push(`- ${c.id}${c.registered ? '' : ' (not in the registry)'}: ${c.count} fix commits`);
    for (const s of c.subjects.slice(0, 3)) lines.push(`    · ${s}`);
  }
  return lines.join('\n');
}

export const readDebtLog = () => (existsSync(DEBT_LOG) ? JSON.parse(readFileSync(DEBT_LOG, 'utf8')) : {});
export function recentSubjects() {
  try { return execFileSync('git', ['log', '--since=30.days', '--format=%s'], { cwd: ROOT, encoding: 'utf8' }).split('\n').filter(Boolean); }
  catch { return []; }
}
export const report = () => buildReport({ subjects: recentSubjects(), log: readDebtLog() });

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [cmd, flag] = process.argv.slice(2);
  if (cmd === 'index') {
    const doc = readFileSync(DOC, 'utf8');
    const next = withIndex(doc, readRegistry());
    if (flag === '--check') { if (next !== doc) { console.error('docs/RULES.md index is stale: node tools/agents/rules.mjs index'); process.exit(1); } console.log('index fresh'); }
    else { writeFileSync(DOC, next); console.log('docs/RULES.md index built'); }
  } else if (cmd === 'problems') {
    const p = problems(); console.log(p.length ? p.join('\n') : 'no problems'); process.exit(p.length ? 1 : 0);
  } else if (cmd === 'report') {
    const args = process.argv.slice(3), rep = report();
    if (args.includes('--record')) {
      const log = readDebtLog();
      log[rep.date] = Object.fromEntries(rep.debt.map(d => [d.id, d.count]));
      writeFileSync(DEBT_LOG, JSON.stringify(log, null, 1) + '\n');
    }
    console.log(args.includes('--json') ? JSON.stringify(rep, null, 1) : formatReport(rep));
  } else { console.log('Usage: node tools/agents/rules.mjs index [--check] | problems | report [--json] [--record]'); }
}
