/** Los minijuegos en un idioma: lo de BASE más sus textos. */
export const minijuegos = (lang = 'es') => {
  const L = LOCALES[lang] || ES;
  return Object.fromEntries(Object.entries(BASE).map(([id, b]) => [id, { ...b, ...L.juegos[id] }]));
};
